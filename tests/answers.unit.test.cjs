// Answers: the person's questions, paired with their replies — and only the
// person's: not what hop or an agent typed, a loop, or the agent app's own.
const test = require('node:test');
const assert = require('node:assert/strict');
const { classify, describe, emptyStore, normalizeStore, add, markRead, archive, move, unreadBySession, prune, humanTurn, ARCHIVE_KEEP_MS, KEEP_MAX } = require('../lib/answers');

const NOW = Date.parse('2026-11-12T06:00:00.000Z');
const M = 60_000;

test('the person\'s own words are a question; the agent app\'s own turns are not', () => {
  assert.equal(classify('why is the validation loss flat after epoch 3?', { at: NOW }), 'person');
  assert.equal(classify('sure', { at: NOW }), 'person');
  for (const t of [
    '<task-notification>\n<task-id>b1</task-id>',
    '<command-name>/loop</command-name>',
    '<local-command-stdout>ok</local-command-stdout>',
    'Caveat: The messages below were generated by the user while running local commands.',
    '<system-reminder>x</system-reminder>',
    '   ',
    ''
  ]) assert.equal(classify(t, { at: NOW }), 'internal', t);
  assert.equal(classify('[hop message from session "surf" (a Codex agent, not your user). To answer…] rerun', { at: NOW }), 'agent');
  assert.equal(classify('[CEO] sure, continue with the sweep', { at: NOW }), 'agent');
});

test('what hop or an agent typed through hop is theirs; the person\'s queued message is the person\'s', () => {
  const typed = [
    { at: NOW - 2 * M, text: 'Check the queue depth on node 06 and report' },
    { at: NOW - 2 * M, text: '\r' },
    // An agent typing in pieces through the terminal API.
    { at: NOW - M, text: 'please summarise ' }, { at: NOW - M, text: 'the run' }
  ];
  assert.equal(classify('Check the queue depth on node 06 and report', { at: NOW, typed }), 'typed');
  assert.equal(classify('please summarise the run', { at: NOW, typed }), 'typed');
  // Long ago: no longer an explanation.
  assert.equal(classify('Check the queue depth on node 06 and report', { at: NOW + 20 * M, typed }), 'person');
  // The web's "send when done": typed by hop, marked as the person's.
  const queued = [...typed, { at: NOW - M, text: 'what was the final AUC?', person: true }, { at: NOW - M, text: 'what was the final AUC?' }];
  assert.equal(classify('what was the final AUC?', { at: NOW, typed: queued }), 'person');
});

test('the same long prompt again within hours is a loop, a short reply is not', () => {
  const asked = [{ at: NOW - 30 * M, text: 'Check every training run and push the idle ones forward.' }, { at: NOW - 30 * M, text: 'continue' }];
  assert.equal(classify('Check every training run and push the idle ones forward.', { at: NOW, asked }), 'repeat');
  assert.equal(classify('continue', { at: NOW, asked }), 'person');
  assert.equal(classify('Check every training run and push the idle ones forward.', { at: NOW + 7 * 60 * M, asked }), 'person', 'a day later it is asked again');
});

test('answers are kept unread until read, by id, by session, or all', () => {
  const store = emptyStore();
  add(store, { id: 'a1', session: 's_a', question: 'q1', askedAt: NOW - 5 * M, answer: 'r1', answeredAt: NOW - 4 * M }, NOW);
  add(store, { id: 'a2', session: 's_a', question: 'q2', askedAt: NOW - 3 * M, answer: 'r2', answeredAt: NOW - 2 * M }, NOW);
  add(store, { id: 'b1', session: 's_b', question: 'q3', askedAt: NOW - 3 * M, answer: 'r3', answeredAt: NOW - M }, NOW);
  assert.deepEqual(unreadBySession(store), { s_a: 2, s_b: 1 });
  assert.equal(markRead(store, { ids: ['a1'] }, NOW), 1);
  assert.deepEqual(unreadBySession(store), { s_a: 1, s_b: 1 });
  assert.equal(markRead(store, { session: 's_a' }, NOW), 1);
  assert.equal(markRead(store, { all: true }, NOW), 1);
  assert.deepEqual(unreadBySession(store), {});
  assert.equal(markRead(store, { all: true }, NOW), 0, 'nothing left');
  // A bad file reads as empty.
  assert.deepEqual(normalizeStore({ items: [{ id: 'x' }, { id: 'ok', session: 's', askedAt: NOW, question: 'q1' }] }).items.map((a) => a.id), ['ok']);
});

test('what runs on its own is not a question: a loop\'s runs, Claude\'s agents, the Codex app\'s catch-up', () => {
  // /loop as it fires again — its agent rewrites the prompt each run.
  assert.equal(classify('/loop Shepherd the fleet. STATE 03:02: outage continues (65 min)', { at: NOW }), 'loop');
  assert.equal(classify('<<autonomous-loop-dynamic>>', { at: NOW }), 'loop');
  assert.equal(classify('<agent-message from="abacfb">\n[Subagent hand-back] The text below…', { at: NOW }), 'agent');
  assert.equal(classify('Another Claude session sent a message:\n<agent-message from="a1">', { at: NOW }), 'agent');
  assert.equal(classify('The coordinator sent a message while you were working:\nResume lane C', { at: NOW }), 'agent');
  assert.equal(classify('Your claude.ai usage limit has reset. Continue the task', { at: NOW }), 'internal');
  assert.equal(classify('Write a brief catch-up for a user returning to this task. Return JSON with summary', { at: NOW }), 'internal');
  // "loop" in the middle of a question is a question.
  assert.equal(classify('should the /loop run every hour?', { at: NOW }), 'person');
});

test('a paste is read for what is inside: hop\'s messages arrive pasted', () => {
  const wrapped = '\n\n<pasted_content id="81a8">\n[hop message from session "surf" (a Claude agent, not your user).] rerun\n</pasted_content id="81a8">\n';
  assert.equal(classify(wrapped, { at: NOW }), 'agent');
  // A long paste comes in pieces under one id; hop typed the whole of it.
  const sent = 'Junction-model training has news (probe ops/e2e_event.sh: arm milestones). acceptor rows 0.639 / 0.883';
  const pieces = `\n\n<pasted_content id="cba7">\n${sent.slice(0, 60)}\n</pasted_content id="cba7">\n\n\n<pasted_content id="cba7">\n${sent.slice(60)}\n</pasted_content id="cba7">\n`;
  assert.equal(classify(pieces, { at: NOW, typed: [{ at: NOW - M, text: `\x1b[200~${sent}\x1b[201~` }] }), 'typed');
  // The person's own paste, with their words around it, is theirs.
  assert.equal(classify('can you check this model?\n\n<pasted_content id="e014">\nclass Net(nn.Module): …\n</pasted_content id="e014">\n', { at: NOW }), 'person');
});

test('where the agent app says a turn\'s prompts came from, a turn no person started is not kept', () => {
  assert.equal(humanTurn(['human']), true);
  assert.equal(humanTurn(['human', 'task-notification', 'peer']), true, 'a question with notices landing in its turn');
  assert.equal(humanTurn(['scheduled']), false);
  assert.equal(humanTurn(['task-notification', 'peer', 'coordinator', 'auto-continuation']), false);
  assert.equal(humanTurn(['scheduled', 'unknown']), null, 'part of the turn out of sight: the text decides');
  assert.equal(humanTurn(['sdk']), null, 'a kind hop does not know: the text decides');
  assert.equal(humanTurn(undefined), null);
  assert.equal(humanTurn([]), null);
});

test('answers kept before hop said where a prompt came from are filed when read back', () => {
  const loop = 'Self-paced training loop, allowed to adjust and resubmit runs without asking: keep going until it converges.';
  const kept = normalizeStore({ items: [
    { id: 'q', session: 's', askedAt: NOW, question: 'why is the loss flat?' },
    { id: 'l', session: 's', askedAt: NOW + 1, question: '/loop Shepherd the fleet.' },
    { id: 'p', session: 's', askedAt: NOW + 2, question: '\n\n<pasted_content id="1">\n[hop message from session "x"] hi\n</pasted_content id="1">' },
    { id: 'c', session: 's', askedAt: NOW + 3, question: 'Write a brief catch-up for a user returning to this task.' },
    { id: 'r1', session: 's', askedAt: NOW + 4, question: loop },
    { id: 'r2', session: 's', askedAt: NOW + 4 + 3600_000, question: loop },
    // The person sending the same long message again the next day is still the person.
    { id: 'r3', session: 's', askedAt: NOW + 4 + 30 * 3600_000, question: loop }
  ] });
  // The agent app's own notice is nobody's; the rest keep, each on its side.
  assert.deepEqual(kept.items.map((a) => [a.id, a.from, a.source, a.by]), [
    ['q', 'you', 'you', null], ['l', 'agents', 'loop', null], ['p', 'agents', 'message', 'x'],
    ['r1', 'you', 'you', null], ['r2', 'agents', 'repeat', null], ['r3', 'you', 'you', null]
  ]);
  // Filed once, kept as filed.
  assert.deepEqual(normalizeStore(kept).items.map((a) => a.from), ['you', 'agents', 'agents', 'you', 'agents', 'you']);
});

test('where a prompt came from: the sender, a check-back and who set it, a schedule, the person\'s queued words', () => {
  const at = NOW;
  assert.deepEqual(describe('[hop message from session "plotter" (a Claude agent, not your user). To answer…] check the plot', { at }),
    { kind: 'agent', from: 'agents', source: 'message', by: 'plotter' });
  assert.equal(describe("[hop message from an agent outside hop, not your user] From pulse-bot's morning pulse (2026-11-20): Protect", { at }).by, 'pulse-bot');
  assert.equal(describe('[CEO] sure, keep going', { at }).by, 'CEO');
  // A check-back's record outlives a restart; it lands a little after the prompt.
  const typed = [{ at: at + 30_000, slackMs: 120_000, text: 'Review the sweep from ~/Code/sweeps', person: false, source: 'scheduled', by: 'coordinator' }];
  assert.deepEqual(describe('Review the sweep from ~/Code/sweeps', { at, typed }), { kind: 'typed', from: 'agents', source: 'scheduled', by: 'coordinator' });
  const mine = [{ at: at - 1000, text: 'run the eval again', person: true }];
  assert.deepEqual(describe('run the eval again', { at, typed: mine }), { kind: 'person', from: 'you', source: 'queued', by: null });
  assert.deepEqual(describe('<task-notification>done</task-notification>', { at }).from, null);
});

test('only the person\'s own questions count toward a session\'s unread badge', () => {
  const store = emptyStore();
  add(store, { id: 'a', session: 's', question: 'q?', askedAt: NOW, answer: 'x', from: 'you' }, NOW);
  add(store, { id: 'b', session: 's', question: 'msg', askedAt: NOW, answer: 'y', from: 'agents', source: 'message', by: 'plotter' }, NOW);
  assert.deepEqual(unreadBySession(store), { s: 1 });
  assert.deepEqual(store.items.map((a) => [a.from, a.source, a.by]), [['you', 'you', null], ['agents', 'message', 'plotter']]);
});

test('kept like mail: read answers stay until archived, archived ones go a month later', () => {
  const store = emptyStore();
  const YEAR = 365 * 24 * 3600_000;
  add(store, { id: 'old', session: 's', question: 'q0', askedAt: NOW - YEAR, answer: 'r', answeredAt: NOW - YEAR }, NOW - YEAR);
  add(store, { id: 'a', session: 's', question: 'q1', askedAt: NOW - 2 * M, answer: 'r', answeredAt: NOW - M }, NOW);
  markRead(store, { all: true }, NOW);
  assert.equal(prune(store, NOW), 0, 'read, not archived: stays, however old');
  assert.equal(archive(store, { ids: ['old'] }, NOW), 1);
  assert.equal(archive(store, { ids: ['old'] }, NOW), 0, 'already archived');
  assert.equal(archive(store, { ids: ['a'], archived: false }, NOW), 0, 'already in the inbox');
  // Archiving reads it; putting it back keeps it read.
  add(store, { id: 'u', session: 's', question: 'q2', askedAt: NOW, answer: 'r', answeredAt: NOW }, NOW);
  assert.deepEqual(unreadBySession(store), { s: 1 });
  archive(store, { ids: ['u'] }, NOW);
  assert.ok(store.items.find((a) => a.id === 'u').readAt);
  assert.deepEqual(unreadBySession(store), {});
  archive(store, { ids: ['u'], archived: false }, NOW);
  assert.equal(store.items.find((a) => a.id === 'u').archivedAt, null);
  assert.equal(prune(store, NOW + ARCHIVE_KEEP_MS - M), 0);
  assert.equal(prune(store, NOW + ARCHIVE_KEEP_MS + M), 1);
  assert.deepEqual(store.items.map((a) => a.id), ['a', 'u']);
});

test('past a tab\'s limit the archived go first, then the read, then the oldest unread; the other tab keeps its own', () => {
  const store = emptyStore();
  const n = KEEP_MAX.agents;
  for (let i = 0; i < n; i++) store.items.push({ id: `g${i}`, session: 's', from: 'agents', question: 'q', askedAt: NOW + i, answeredAt: NOW + i, readAt: null, archivedAt: null });
  store.items.push({ id: 'mine', session: 's', from: 'you', question: 'q', askedAt: NOW - 1, answeredAt: NOW - 1, readAt: null, archivedAt: null });
  store.items[5].archivedAt = NOW + 9; store.items[5].readAt = NOW + 9;
  store.items[7].readAt = NOW + 9;
  store.items.push({ id: 'g-new', session: 's', from: 'agents', question: 'q', askedAt: NOW + n, answeredAt: NOW + n, readAt: null, archivedAt: null });
  store.items.push({ id: 'g-newer', session: 's', from: 'agents', question: 'q', askedAt: NOW + n + 1, answeredAt: NOW + n + 1, readAt: null, archivedAt: null });
  store.items.push({ id: 'g-newest', session: 's', from: 'agents', question: 'q', askedAt: NOW + n + 2, answeredAt: NOW + n + 2, readAt: null, archivedAt: null });
  assert.equal(prune(store, NOW + n + 3), 3);
  const ids = new Set(store.items.map((a) => a.id));
  assert.equal(ids.has('g5') || ids.has('g7') || ids.has('g0'), false);
  assert.ok(ids.has('g1') && ids.has('mine') && ids.has('g-newest'));
});

test('its person can move a turn to the other tab; only the person\'s own count on the badge', () => {
  const store = emptyStore();
  add(store, { id: 'l', session: 's', question: 'Autonomous loop: keep going', askedAt: NOW, answer: 'r', answeredAt: NOW }, NOW);
  assert.deepEqual(unreadBySession(store), { s: 1 });
  assert.equal(move(store, { ids: ['l'], from: 'agents' }, NOW), 1);
  assert.equal(move(store, { ids: ['l'], from: 'agents' }, NOW), 0);
  assert.equal(move(store, { ids: ['l'], from: 'nobody' }, NOW), 0);
  assert.equal(store.items[0].movedAt, NOW);
  assert.deepEqual(unreadBySession(store), {});
});

test('a legacy store\'s schedule: a long prompt kept three times or more, a little reworded, is not the person\'s', () => {
  const body = 'Self-paced training loop: check the newest run, adjust and resubmit without asking, and log what changed. '.repeat(3);
  const mine = 'please rerun the comparison with the same seeds and tell me whether the difference survives the rerun before anything else. '.repeat(2);
  const kept = normalizeStore({ items: [
    { id: 'r1', session: 'm', askedAt: NOW, question: `${body} Run 1.` },
    { id: 'r2', session: 'm', askedAt: NOW + 4 * 3600_000 * 2, question: `${body} Run 2: the eval improved.` },
    { id: 'r3', session: 'm', askedAt: NOW + 4 * 3600_000 * 4, question: `<pasted_content id="1">${body}</pasted_content id="1"> Run 3.` },
    { id: 'other', session: 'x', askedAt: NOW, question: `${body} Run 1.` },
    { id: 'p1', session: 'm', askedAt: NOW + 1, question: mine },
    { id: 'p2', session: 'm', askedAt: NOW + 8 * 3600_000, question: mine }
  ] });
  assert.deepEqual(Object.fromEntries(kept.items.map((a) => [a.id, `${a.from}/${a.source}`])), {
    r1: 'agents/repeat', r2: 'agents/repeat', r3: 'agents/repeat', other: 'you/you', p1: 'you/you', p2: 'you/you'
  });
});
