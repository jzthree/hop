// Answers: the person's questions, paired with their replies — and only the
// person's: not what hop or an agent typed, a loop, or the agent app's own.
const test = require('node:test');
const assert = require('node:assert/strict');
const { classify, emptyStore, normalizeStore, add, markRead, unreadBySession, prune, KEEP_MS } = require('../lib/answers');

const NOW = Date.parse('2026-11-12T06:00:00.000Z');
const M = 60_000;

test('the person\'s own words are a question; the agent app\'s own turns are not', () => {
  assert.equal(classify('why is the validation loss flat after epoch 3?', { at: NOW }), 'person');
  assert.equal(classify('sure', { at: NOW }), 'person');
  for (const t of [
    '<task-notification>\n<task-id>b1</task-id>',
    '<command-name>/loop</command-name>',
    '<local-command-stdout>ok</local-command-stdout>',
    'Caveat: The messages below were generated by the user while running local commands.',
    '<system-reminder>x</system-reminder>',
    '   ',
    ''
  ]) assert.equal(classify(t, { at: NOW }), 'internal', t);
  assert.equal(classify('[hop message from session "surf" (a Codex agent, not your user). To answer…] rerun', { at: NOW }), 'agent');
  assert.equal(classify('[CEO] sure, continue with the sweep', { at: NOW }), 'agent');
});

test('what hop or an agent typed through hop is theirs; the person\'s queued message is the person\'s', () => {
  const typed = [
    { at: NOW - 2 * M, text: 'Check the queue depth on node 06 and report' },
    { at: NOW - 2 * M, text: '\r' },
    // An agent typing in pieces through the terminal API.
    { at: NOW - M, text: 'please summarise ' }, { at: NOW - M, text: 'the run' }
  ];
  assert.equal(classify('Check the queue depth on node 06 and report', { at: NOW, typed }), 'typed');
  assert.equal(classify('please summarise the run', { at: NOW, typed }), 'typed');
  // Long ago: no longer an explanation.
  assert.equal(classify('Check the queue depth on node 06 and report', { at: NOW + 20 * M, typed }), 'person');
  // The web's "send when done": typed by hop, marked as the person's.
  const queued = [...typed, { at: NOW - M, text: 'what was the final AUC?', person: true }, { at: NOW - M, text: 'what was the final AUC?' }];
  assert.equal(classify('what was the final AUC?', { at: NOW, typed: queued }), 'person');
});

test('the same long prompt again within hours is a loop, a short reply is not', () => {
  const asked = [{ at: NOW - 30 * M, text: 'Check every training run and push the idle ones forward.' }, { at: NOW - 30 * M, text: 'continue' }];
  assert.equal(classify('Check every training run and push the idle ones forward.', { at: NOW, asked }), 'repeat');
  assert.equal(classify('continue', { at: NOW, asked }), 'person');
  assert.equal(classify('Check every training run and push the idle ones forward.', { at: NOW + 7 * 60 * M, asked }), 'person', 'a day later it is asked again');
});

test('answers are kept unread until read, by id, by session, or all', () => {
  const store = emptyStore();
  add(store, { id: 'a1', session: 's_a', question: 'q1', askedAt: NOW - 5 * M, answer: 'r1', answeredAt: NOW - 4 * M }, NOW);
  add(store, { id: 'a2', session: 's_a', question: 'q2', askedAt: NOW - 3 * M, answer: 'r2', answeredAt: NOW - 2 * M }, NOW);
  add(store, { id: 'b1', session: 's_b', question: 'q3', askedAt: NOW - 3 * M, answer: 'r3', answeredAt: NOW - M }, NOW);
  assert.deepEqual(unreadBySession(store), { s_a: 2, s_b: 1 });
  assert.equal(markRead(store, { ids: ['a1'] }, NOW), 1);
  assert.deepEqual(unreadBySession(store), { s_a: 1, s_b: 1 });
  assert.equal(markRead(store, { session: 's_a' }, NOW), 1);
  assert.equal(markRead(store, { all: true }, NOW), 1);
  assert.deepEqual(unreadBySession(store), {});
  assert.equal(markRead(store, { all: true }, NOW), 0, 'nothing left');
  // Two weeks, oldest first; a bad file reads as empty.
  add(store, { id: 'old', session: 's_a', question: 'q', askedAt: NOW - KEEP_MS - 2 * M, answer: '', answeredAt: NOW - KEEP_MS - M }, NOW);
  prune(store, NOW);
  assert.equal(store.items.some((a) => a.id === 'old'), false);
  assert.deepEqual(normalizeStore({ items: [{ id: 'x' }, { id: 'ok', session: 's', askedAt: NOW }] }).items.map((a) => a.id), ['ok']);
});
